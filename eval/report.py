"""Run the evaluation and write ``eval/reports/<dataset>-<provider>-<git-sha>.{json,md}``.

    uv run python -m eval.report --provider heuristic --check     # CI regression gate
    uv run python -m eval.report --provider ollama                # reported, never gated

``--check`` compares metrics with ``eval/thresholds.json`` and exits 1 on a regression.
Detection metrics are reported separately from investigation metrics (PLAN.md section 4).
Results on synthetic data say nothing about real networks.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess  # noqa: S404  (eval tooling only; netpulse/ never shells out)
import sys
from datetime import UTC, datetime
from pathlib import Path

from eval import detection_benchmark, investigation_benchmark

ROOT = Path(__file__).resolve().parent.parent
THRESHOLDS = ROOT / "eval" / "thresholds.json"
REPORTS_DIR = ROOT / "eval" / "reports"
DATASET = "v1"
NOTICE = "SYNTHETIC DATA: results describe a simulated network and do not transfer to real networks."


def git_sha() -> str:
    if sha := os.environ.get("GITHUB_SHA"):
        return sha[:7]
    try:
        out = subprocess.run(  # noqa: S603
            ["git", "rev-parse", "--short", "HEAD"],  # noqa: S607
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=True,
            timeout=10,
        )
        return out.stdout.strip() or "nogit"
    except (OSError, subprocess.SubprocessError):
        return "nogit"


def check_thresholds(metrics: dict, detection: dict, thresholds: dict) -> list[str]:
    """Return human-readable regressions. ``min`` keys must stay at or above, ``max`` keys at or below."""
    values = {**metrics, "detection_precision": detection["precision"], "detection_recall": detection["recall"]}
    failures = []
    for key, bound in thresholds.get("min", {}).items():
        if values[key] < bound:
            failures.append(f"{key} = {values[key]:.3f} is below the minimum {bound}")
    for key, bound in thresholds.get("max", {}).items():
        if values[key] > bound:
            failures.append(f"{key} = {values[key]:.3f} is above the maximum {bound}")
    return failures


def build_report(provider: str) -> dict:
    investigation = investigation_benchmark.run(provider)
    detection = detection_benchmark.run()
    return {
        "dataset": DATASET,
        "provider": provider,
        "generators_used": investigation["generators_used"],
        "git_sha": git_sha(),
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "notice": NOTICE,
        "detection": {k: v for k, v in detection.items() if k != "cases"} | {"cases": detection["cases"]},
        "investigation": investigation["metrics"],
        "cases": investigation["cases"],
    }


def render_markdown(report: dict, failures: list[str]) -> str:
    inv, det = report["investigation"], report["detection"]
    lines = [
        f"# NetPulse evaluation: {report['dataset']} / {report['provider']} / {report['git_sha']}",
        "",
        f"> {report['notice']}",
        "",
        f"Hypotheses were generated by: {', '.join(report['generators_used']) or 'none'} "
        f"(requested provider: {report['provider']}).",
        "",
        "## Detection layer",
        "",
        f"- precision **{det['precision']:.3f}**, recall **{det['recall']:.3f}**",
        f"- predicted {det['predicted']}, observable truth {det['truth_observable']}, "
        f"unobservable truth {det['truth_unobservable']}, unconfirmed signals {det['unconfirmed_signals']}",
        "",
        "## Investigation layer",
        "",
        "| Metric | Value |",
        "|---|---|",
    ]
    for key, value in inv.items():
        lines.append(f"| {key} | {value:.3f} |" if isinstance(value, float) else f"| {key} | {value} |")
    lines += ["", "Cost is $0: heuristic and local providers report no paid tokens.", ""]
    lines += ["## Regression gate", ""]
    lines += [f"- FAIL: {f}" for f in failures] if failures else ["- all thresholds met"]
    lines += [
        "",
        "## Per-case results and failure analysis",
        "",
        "| Case | Scenario | Outcome | Top-1 | Escalate | Notes |",
    ]
    lines.append("|---|---|---|---|---|---|")
    for c in report["cases"]:
        top1 = "n/a" if c["top1"] is None else ("yes" if c["top1"] else "NO")
        esc = "ok" if c["predicted_escalate"] == c["should_escalate"] else "WRONG"
        notes = "; ".join(c["failures"]).replace("|", "/") or "-"
        lines.append(f"| {c['case_id']} | {c['scenario']} | {c['outcome']} | {top1} | {esc} | {notes} |")
    lines.append("")
    return "\n".join(lines)


def write_report(report: dict, failures: list[str], out_dir: Path = REPORTS_DIR) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    stem = f"{report['dataset']}-{report['provider']}-{report['git_sha']}"
    json_path, md_path = out_dir / f"{stem}.json", out_dir / f"{stem}.md"
    json_path.write_text(json.dumps(report, indent=2, sort_keys=True, default=str) + "\n")
    md_path.write_text(render_markdown(report, failures))
    return json_path, md_path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--provider", choices=["heuristic", "ollama"], default="heuristic")
    parser.add_argument("--check", action="store_true", help="exit 1 if a metric regresses past eval/thresholds.json")
    parser.add_argument("--out-dir", type=Path, default=REPORTS_DIR)
    args = parser.parse_args(argv)

    report = build_report(args.provider)
    failures = []
    if args.check:
        if args.provider != "heuristic":
            print("note: only the heuristic provider is gated; ollama results are reported only")
        else:
            failures = check_thresholds(
                report["investigation"], report["detection"], json.loads(THRESHOLDS.read_text())
            )
    json_path, md_path = write_report(report, failures, args.out_dir)
    print(f"wrote {json_path} and {md_path}")
    for failure in failures:
        print(f"REGRESSION: {failure}", file=sys.stderr)
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
